/**
 * Parody shop names (STORES2). Deterministic from (type, shop id, seed): the same lot always gets the same name, with
 * no shared state, so the real map can stream lots in any order.
 *
 * What a parody name does: it jokes on a KIND of name or a naming habit (the "Famous Original" habit, the number-one
 * habit, "New" meaning "old", the possessive nobody owns). It is never the name of a real business, a chain or a
 * brand, and it does not mock a person or a group. Parts below are plain words, street names, invented first names
 * and trade words; the hand-written standouts are one-off jokes.
 *
 * Every name must read as its trade: the sign text has to classify (`classifyArchetype`) to the type's art archetype
 * and cuisine, because the awning and lit-box painters take their icons and stripes from the words. `shopIdentity`
 * checks this itself and re-rolls a part that breaks it, so a tagline word like "CUTS" never turns a pizzeria into a
 * barber.
 */
