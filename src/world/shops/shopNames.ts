function h32(s: string): number {
  // Rng.hash is fine for seeding but its low bits correlate for ids that differ in a digit or two; finish with a mixer
  let h = Rng.hash(s) >>> 0;
  h ^= h >>> 16; h = Math.imul(h, 0x85ebca6b); h ^= h >>> 13; h = Math.imul(h, 0xc2b2ae35); h ^= h >>> 16;
  return h >>> 0;
}
function pick<T>(a: readonly T[], h: number): T {
  return a[h % a.length];
}

/** One main-name candidate. `salt` re-rolls the pattern and parts together. */
function mainName(type: ShopType, id: string, seed: number, salt: number): string {
  const lex = LEX[type];
  const base = h32(`${seed}|${id}|${type}|${salt}`);
  const h1 = h32(`${base}a`), h2 = h32(`${base}b`), h3 = h32(`${base}c`), h4 = h32(`${base}d`), h5 = h32(`${base}e`);
  const core = pick(lex.core, h2);
  const roll = h1 % 100;
  if (roll < 1 && salt < 1) return pick(lex.stand, h3);
  if (roll < 11) return `${pick(ADJ, h3)} ${core}`;
  if (roll < 22) return `${pick(PLACES, h3)} ${core}`;
  if (roll < 29) return `${pick(lex.pre, h3)} ${core}`;
  if (roll < 35) return `${pick(OWNER, h3)} ${core}`;
  if (roll < 38) return `${pick(NUM, h3)} ${core}`;
  if (roll < 65) return `${pick(ADJ, h3)} ${pick(PLACES, h4)} ${core}`;
  if (roll < 80) return `${pick(lex.pre, h3)} ${pick(PLACES, h5)} ${core}`;
  if (roll < 92) return `${pick(ADJ, h3)} ${pick(lex.pre, h4)} ${core}`;
  return `${pick(OWNER, h3)} ${pick(lex.pre, h4)} ${core}`;
}

function tidy(s: string): string {
  return s.replace(/\s+/g, ' ').trim();
}

/** Does `text` read as this type to the art code: right archetype and, for restaurants, right cuisine icons? */
export function readsAsType(type: ShopType, text: string): boolean {
  const info = SHOP_TYPES[type];
  const arch = classifyArchetype(text);
  if (arch !== info.archetype) return false;
  if (info.archetype === 'kitchen') {
    const cu = cuisineOf(text);
    if (info.cuisine !== cu) return false;
  }
  return true;
}

/** The identity of one shop: deterministic from (type, id, seed). */
export function shopIdentity(type: ShopType, id: string, seed = 0): ShopIdentity {
  const lex = LEX[type];
  const t0 = h32(`${seed}|${id}|${type}|tag`);
  for (let salt = 0; salt < 24; salt++) {
    const main = tidy(mainName(type, id, seed, salt));
    if (main.length > 38 && salt < 20) continue;
    // the tagline is re-rolled on its own: a word in it must not change the reading of the whole sign
    for (let k = 0; k < lex.tag.length; k++) {
      const tagline = lex.tag[(t0 + k) % lex.tag.length];
      const name = `${main}  ·  ${tagline}`;
      if (!readsAsType(type, name)) continue;
      const c0 = h32(`${seed}|${id}|copy`);
      let signCopy = '';
      for (let j = 0; j < lex.copy.length && !signCopy; j++) {
        const c = lex.copy[(c0 + j) % lex.copy.length];
        if (readsAsType(type, c)) signCopy = c;
      }
      if (!signCopy) continue;
      return { type, name, main, tagline, signCopy };
    }
  }
  // cannot happen with the shipped lexicon (a test walks every type); the fallback is a plain, correct sign
  const main = tidy(`${pick(PLACES, h32(id))} ${lex.core[0]}`);
  return { type, name: main, main, tagline: '', signCopy: lex.copy[0] };
}

/** Number of distinct main names the lexicon can make for a type (upper bound; used by the tests). */
export function nameSpace(type: ShopType): number {
  const l = LEX[type];
  const c = l.core.length;
  return c * ADJ.length + c * PLACES.length + c * l.pre.length + c * OWNER.length + c * NUM.length + c * ADJ.length * PLACES.length
    + c * l.pre.length * PLACES.length + c * ADJ.length * l.pre.length + c * OWNER.length * l.pre.length + l.stand.length;
}

/** Every hand-written standout and tagline of a type (for the tests and the credits check). */
export function lexiconOf(type: ShopType): { standouts: readonly string[]; taglines: readonly string[]; copies: readonly string[]; cores: readonly string[] } {
  const l = LEX[type];
  return { standouts: l.stand, taglines: l.tag, copies: l.copy, cores: l.core };
}

/** The type of a shop on the default grid map or the real map: from a lot's store kind and cuisine, deterministic. */
export function pickShopType(
  candidates: readonly { type: ShopType; weight: number }[], id: string, seed = 0,
): ShopType {
  let total = 0;
  for (const c of candidates) total += c.weight;
  let x = ((h32(`${seed}|${id}|type`) % 10000) / 10000) * total;
  for (const c of candidates) {
    x -= c.weight;
    if (x < 0) return c.type;
  }
  return candidates[candidates.length - 1].type;
}

