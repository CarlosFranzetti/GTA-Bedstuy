import fs from 'node:fs'; import path from 'node:path'; import { createServer } from 'vite';
const ROOT='/home/user/GTA-Bedstuy';
const vite = await createServer({ configFile:false, root:ROOT, appType:'custom', logLevel:'silent', resolve:{alias:{'@':path.join(ROOT,'src')}}, server:{middlewareMode:true,ws:false}, optimizeDeps:{noDiscovery:true}});
const THREE = await vite.ssrLoadModule('three');
const { RoadNet } = await vite.ssrLoadModule('/src/world/roadnet/RoadNet.ts');
const { Rng } = await vite.ssrLoadModule('/src/core/Rng.ts');
const d = await vite.ssrLoadModule('/src/world/roadnet/derive.ts');
const sw = await vite.ssrLoadModule('/src/world/roadnet/sidewalks.ts');
const ch = await vite.ssrLoadModule('/src/world/roadnet/chunksReal.ts');
const pr = await vite.ssrLoadModule('/src/world/roadnet/propsReal.ts');
const sg = await vite.ssrLoadModule('/src/world/roadnet/signalPhases.ts');
const f = ROOT+'/src/world/data/roadnet-r4.json';
const net = RoadNet.fromJson(JSON.parse(fs.readFileSync(f,'utf8')));
const ctl = JSON.parse(fs.readFileSync(ROOT+'/src/world/data/roadnet-controls-r4.json','utf8'));
const der=d.deriveGeometry(net); const sws=sw.buildSidewalkGraph(net,der); const layout=ch.chunkLayoutFromBounds(net.bounds, false);
const cache=new Map(); const mk=()=>new THREE.MeshBasicMaterial();
const lib={ get(k,v=0){const key=k+':'+v;let m=cache.get(key);if(!m){m=mk();cache.set(key,m);}return m;}, awning:mk, sign:(t)=>mk(), carPaint:mk, setNight:()=>{} };
const controls=sg.nodeControl(net,ctl);
const run=(region)=>{const t=performance.now(); const r=pr.buildRealProps({net,derived:der,sidewalks:sws,materials:lib,rng:new Rng(5),layout,controls,tier:'low',regionFn:region}); return [Math.round(performance.now()-t), r.stats.meshes, r.stats.triangles, r.stats.trees,r.stats.lamps];};
console.log('whole R4', run());
for (const [x,z] of [[0,0],[-1400,-300],[2600,-600]]) console.log('tile',x,z, run((p)=>p.x>=x&&p.x<x+512&&p.z>=z&&p.z<z+512));
await vite.close();
