#!/usr/bin/env node
/**
 * build-places-real: maps every place the game uses on the stylised grid onto the real map.
 *
 *   node scripts/build-places-real.mjs            -> src/world/data/places-real.json
 *
 * Inputs: src/world/data/roadnet-core.json, raw/lots-real-r1r2a.json (NYC open data: MapPLUTO, building footprints),
 * bedstuy.json (the parody POIs), and the mission/ambient source files (scanned for `'r2c1', 'W', 0.4` style spots).
 * Real street names and PLUTO tax-lot ids (BBL) and addresses only; venue, store and brand names stay the game's parodies.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CORE = path.join(ROOT, 'src/world/data/roadnet-core.json');
const LOTS = path.join(ROOT, 'src/world/data/raw/lots-real-r1r2a.json');
const OUT = path.join(ROOT, 'src/world/data/places-real.json');

function walk(dir, out = []) {
  for (const f of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, f.name);
    if (f.isDirectory()) walk(p, out); else if (p.endsWith('.ts')) out.push(p);
  }
  return out;
}

/** the grid's POI kinds -> how a real lot has to look */
const POI_FIT = {
  church: 'church', condo: 'condo', daycare: 'service', funeral: 'service',
};

async function main() {
  const vite = await createServer({
    configFile: false, root: ROOT, appType: 'custom', logLevel: 'silent',
    resolve: { alias: { '@': path.join(ROOT, 'src') } },
    server: { middlewareMode: true, ws: false }, optimizeDeps: { noDiscovery: true },
  });
  try {
    const gridMod = await vite.ssrLoadModule('/src/world/Grid.ts');
    const { RoadNet } = await vite.ssrLoadModule('/src/world/roadnet/RoadNet.ts');
    const { deriveGeometry } = await vite.ssrLoadModule('/src/world/roadnet/derive.ts');
    const { blockFaces } = await vite.ssrLoadModule('/src/world/roadnet/faces.ts');
    const { placeLots } = await vite.ssrLoadModule('/src/world/roadnet/lotsReal.ts');
    const pr = await vite.ssrLoadModule('/src/world/roadnet/placesReal.ts');

    const data = gridMod.loadBedstuyData();
    const grid = gridMod.buildGrid(data);
    const coreRaw = fs.readFileSync(CORE);
    const net = RoadNet.fromJson(JSON.parse(coreRaw.toString('utf8')));
    const lotsJson = JSON.parse(fs.readFileSync(LOTS, 'utf8'));
    const d = deriveGeometry(net);
    const faces = blockFaces(net, d);
    const lots = placeLots(net, d, faces, lotsJson);
    const adOf = new Map(lotsJson.lots.map((l) => [l.bbl, l.ad]));

    const table = {
      meta: { v: 1, core: crypto.createHash('sha1').update(coreRaw).digest('hex'), note: 'grid place -> real map; generated by scripts/build-places-real.mjs; real street names and tax-lot ids only' },
      streets: {}, blocks: {}, pois: {}, interiors: {}, anchors: [],
    };
    for (const s of grid.streets) table.streets[s.id] = s.name;
    for (const b of grid.blocks) {
      const name = (side) => grid.streetById(b.faces.find((f) => f.side === side).streetId).name;
      const names = { n: name('N'), s: name('S'), e: name('E'), w: name('W') };
      const real = pr.matchGridBlock(net, d, faces, names);
      table.blocks[b.id] = { ...names, real: real ?? [] };
    }
    const places = new pr.RealPlaces({ net, derived: d, faces, lots, table, pois: data.pois });
    const used = new Set();
    const entry = (lot, blockId, side, t, kind) => ({ bbl: lot.bbl, ad: adOf.get(lot.bbl) ?? '', at: places.describe(blockId, side, t), t: Math.round(t * 1000) / 1000, ...(kind ? { kind } : {}) });

    // ---- interiors first (they need the best lots), then the shops
    const interiorSpec = {
      // deli door r2c1 W t~0.32 (Throop east side north of Lafayette), home r1c0 E t~0.34, club r1c1 S t~0.27
      home: { block: 'r1c0', side: 'E', t: 0.34, fit: 'home' },
      deli: { block: 'r2c1', side: 'W', t: 0.32, fit: 'shop' },
      club: { block: 'r1c1', side: 'S', t: 0.27, fit: 'club' },
    };
    for (const [id, s] of Object.entries(interiorSpec)) {
      const ch = places.chain(s.block, s.side);
      const pick = ch && pr.pickLotOnChain(places, ch, s.t, s.fit, used);
      if (!pick) throw new Error(`no lot for interior ${id}`);
      used.add(pick.lot.bbl);
      table.interiors[id] = entry(pick.lot, s.block, s.side, s.t, `${s.fit} tier ${pick.tier}, ${Math.round(pick.offsetM)} m from the grid spot`);
    }
    for (const p of data.pois) {
      const ch = places.chain(p.block, p.face);
      const fit = POI_FIT[p.archetype] ?? 'shop';
      const pick = ch && pr.pickLotOnChain(places, ch, p.t, fit, used);
      if (!pick) { console.warn(`poi ${p.id}: no lot on ${p.block}/${p.face}`); continue; }
      used.add(pick.lot.bbl);
      table.pois[p.id] = entry(pick.lot, p.block, p.face, p.t, `${fit} tier ${pick.tier}, ${Math.round(pick.offsetM)} m from the grid spot`);
    }

    // ---- every spot the content uses
    const seen = new Set();
    const spots = [];
    const re = /'(r-?\d+c\d+)',\s*'([NSEW])',\s*(\d*\.\d+|\d+)/g;
    for (const f of walk(path.join(ROOT, 'src/game'))) {
      const txt = fs.readFileSync(f, 'utf8');
      for (const m of txt.matchAll(re)) {
        const k = `${m[1]}/${m[2]}/${Number(m[3])}`;
        if (!seen.has(k)) { seen.add(k); spots.push([m[1], m[2], Number(m[3])]); }
      }
    }
    for (const t of [0.5, 0.62, 0.74, 0.86, 0.96]) { const k = `r2c1/W/${t}`; if (!seen.has(k)) { seen.add(k); spots.push(['r2c1', 'W', t]); } }
    spots.sort((a, b) => (a[0] + a[1]).localeCompare(b[0] + b[1]) || a[2] - b[2]);
    for (const [blockId, side, t] of spots) {
      const ch = places.chain(blockId, side);
      let bbl = '', ad = '', words = `${blockId}/${side}: no real counterpart`;
      if (ch) {
        const { p } = places.frontage(blockId, side, t);
        let best = null;
        for (const pc of ch.pieces) for (const l of places.lots) {
          if (l.wedge || l.block !== pc.block || l.face !== pc.index || l.type === 'vacant') continue;
          const mid = { x: (l.frontA.x + l.frontB.x) / 2, z: (l.frontA.z + l.frontB.z) / 2 };
          const dd = Math.hypot(mid.x - p.x, mid.z - p.z);
          if (!best || dd < best.dd) best = { l, dd };
        }
        words = places.describe(blockId, side, t);
        if (best) { bbl = best.l.bbl; ad = adOf.get(bbl) ?? ''; }
      }
      table.anchors.push([blockId, side, t, bbl, ad, words]);
    }

    const head = JSON.stringify({ meta: table.meta, streets: table.streets, blocks: table.blocks, pois: table.pois, interiors: table.interiors });
    const text = head.slice(0, -1) + ',"anchors":[\n' + table.anchors.map((a) => JSON.stringify(a)).join(',\n') + '\n]}\n';
    fs.writeFileSync(OUT, text);
    console.log(`wrote ${path.relative(ROOT, OUT)}: ${text.length} bytes, ${spots.length} spots, ${Object.keys(table.pois).length} pois, ${Object.keys(table.interiors).length} interiors`);
    const unmatched = Object.entries(table.blocks).filter(([, b]) => !b.real.length).map(([id]) => id);
    console.log('grid blocks with no real counterpart:', unmatched.join(' '));
  } finally { await vite.close(); }
}
main().catch((e) => { console.error(e); process.exit(1); });
