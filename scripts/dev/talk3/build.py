#!/usr/bin/env python3
"""TALK3: builds the talk content JSON from the two plain-text sources next to this file.

  python3 scripts/dev/talk3/build.py
writes src/audio/talk/script-groupchat-bits.json and src/audio/voice/shows/extra-shows.json.
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..', '..'))

GC_CODES = {
    'H': ('host', 'host'), 'S': ('host', 'sidekick'), 'A': ('host', 'announcer'),
    'R1': ('host', 'caller1'), 'R2': ('host', 'caller2'), 'R3': ('host', 'caller3'),
    'P1': ('host', 'caller1'), 'P2': ('host', 'caller2'), 'P3': ('host', 'caller3'),
    'C1': ('caller', 'caller1'), 'C2': ('caller', 'caller2'), 'C3': ('caller', 'caller3'),
    'D': ('ad', 'announcer'), 'N': ('news', 'announcer'), 'J': ('jingle', 'announcer'),
}


def lines_of(path):
    for raw in open(path, encoding='utf-8'):
        s = raw.rstrip('\n')
        if not s.strip() or s.lstrip().startswith('#'):
            continue
        yield s


def head(s):
    parts = [p.strip() for p in s[1:].split('|')]
    return parts


def build_gc():
    out = {'station': 'The Group Chat 99.9', 'note': 'TALK3. Generated by scripts/dev/talk3/build.py from groupchat-bits.txt: edit the source, not this file.',
           'idents': [], 'links': [], 'bits': []}
    bit = None
    for s in lines_of(os.path.join(HERE, 'groupchat-bits.txt')):
        if s.startswith('@ident '):
            out['idents'].append(s[7:].strip()); continue
        if s.startswith('@link '):
            out['links'].append(s[6:].strip()); continue
        if s.startswith('='):
            bid, form, title, topics = head(s)
            bit = {'id': bid, 'form': form, 'title': title, 'topics': [t.strip() for t in topics.split(',') if t.strip()], 'segments': []}
            out['bits'].append(bit); continue
        m = re.match(r'^(H|S|A|R[123]|P[123]|C[123]|D|N|J) ([^:]+): (.+)$', s)
        if not m or bit is None:
            sys.exit(f'bad line: {s}')
        code, who, text = m.groups()
        kind, voice = GC_CODES[code]
        seg = {'id': f"{bit['id']}-{len(bit['segments']) + 1:02d}", 'kind': kind, 'speaker': who.strip(), 'voice': voice, 'text': text.strip()}
        if code.startswith('P'):
            label, real = [x.strip() for x in who.split('~')]
            seg['speaker'] = label
            seg['parodyOf'] = real
        bit['segments'].append(seg)
    return out


def build_wbsy():
    out = {'note': 'TALK3. Generated by scripts/dev/talk3/build.py from wbsy-shows.txt: edit the source, not this file.', 'cast': [], 'shows': [], 'ads': []}
    show = None
    for s in lines_of(os.path.join(HERE, 'wbsy-shows.txt')):
        if s.startswith('@cast '):
            cid, name, kind, voice, speed, fb, persona, catch = [x.strip() for x in s[6:].split('|')]
            role, pitch, rate = fb.split()
            out['cast'].append({'id': cid, 'name': name, 'kind': kind, 'voice': voice, 'speed': float(speed), 'fx': 'studio',
                                'fallback': {'role': role, 'pitch': float(pitch), 'rate': float(rate)}, 'persona': persona, 'catchphrases': [catch]})
            continue
        if s.startswith('='):
            sid, kind, form, title, topics = head(s)
            show = {'id': sid, 'title': title, 'kind': kind, 'form': form, 'host': '', 'topics': [t.strip() for t in topics.split(',') if t.strip()], 'lines': []}
            (out['ads'] if kind == 'ad' else out['shows']).append(show); continue
        m = re.match(r'^([a-z]+)(?: ~ ([^:]+))?: (.+)$', s)
        if not m or show is None:
            sys.exit(f'bad line: {s}')
        who, real, text = m.groups()
        line = {'who': who, 'text': text.strip()}
        if real:
            line['parodyOf'] = real.strip()
        if not show['host'] and who not in ('trent', 'noelle'):
            show['host'] = who
        show['lines'].append(line)
    for sh in out['shows'] + out['ads']:
        if not sh['host']:
            sh['host'] = sh['lines'][0]['who']
    return out


def write(path, data):
    with open(os.path.join(ROOT, path), 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=1)
        f.write('\n')


if __name__ == '__main__':
    gc = build_gc(); wb = build_wbsy()
    write('src/audio/talk/script-groupchat-bits.json', gc)
    write('src/audio/voice/shows/extra-shows.json', wb)
    print('groupchat bits', len(gc['bits']), 'idents', len(gc['idents']), 'links', len(gc['links']))
    print('wbsy shows', len(wb['shows']), 'ads', len(wb['ads']), 'cast', len(wb['cast']))
